"""Compare what the game client can do against what this helper implements.

Reads the Steam client's global-metadata.dat (IL2CPP) and writes docs/game-coverage.md + docs/game-coverage.json.
Run after a game update:
    python3 -I tools/game_coverage.py <global-metadata.dat> [api log containing 'MasterVersion: N']
Needs the generic IL2CPP v29/v31 metadata reader at ~/RustroverProjects/UmamusumeX-rust/tools/il2cpp_metadata.py
(its top half parses types/fields; we exec only that part).
"""
import glob, json, os, re, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.expanduser('~/mementomori-helper-web/src')
READER = os.path.expanduser('~/RustroverProjects/UmamusumeX-rust/tools/il2cpp_metadata.py')
MD = sys.argv[1]
API_LOG = sys.argv[2] if len(sys.argv) > 2 else None  # 可选: API 日志, 用来读当前 MasterVersion

src = open(READER).read()
sys.argv = ['x', MD]
exec(src[:src.index('out = {}')])  # defines types, fields, s(), full(), tname()

game = {}
for k, t in enumerate(types):
    fn = full(k)
    if fn.startswith('Ortega.'):
        game[fn] = [(s(fields[i][0]).replace('k__BackingField', '').strip('<>'), tname(fields[i][1]).split('.')[-1])
                    for i in range(t[8], t[8] + t[18])]

lower1 = lambda x: x[:1].lower() + x[1:]
API_NS = 'Ortega.Share.Data.ApiInterface.'

# ---- game side
game_calls = {}
for fn, flds in game.items():
    m = re.match(re.escape(API_NS) + r'(\w+)\.(\w+)Request$', fn)
    if m and m.group(1) != 'Debug':
        cat, name = m.groups()
        resp = game.get(f'{API_NS}{cat}.{name}Response', [])
        game_calls[(cat, name)] = {'category': cat, 'uri': f'{lower1(cat)}/{lower1(name)}', 'request': flds, 'response': resp}
game_mbs = sorted(n.split('.')[-1] for n in game if n.startswith('Ortega.Share.Master.Data.') and n.endswith('MB'))
game_hubs = sorted(n.split('.')[-1] for n in game if n.startswith('Ortega.Network.MagicOnion.Interface.IMagicOnion') and n.endswith('Receiver'))

# ---- helper side
lib_calls, backend_used = {}, set()
api_code = {f: open(f, encoding='utf-8-sig').read() for f in glob.glob(f'{ROOT}/MementoMori.Api/**/*.cs', recursive=True) if '/obj/' not in f}
for f in glob.glob(f'{ROOT}/MementoMori.Ortega/Share/Data/ApiInterface/**/*Request.cs', recursive=True):
    m = re.search(r'Ortega(?:Api|Auth)\("([^"]+)"', open(f, encoding='utf-8-sig').read())
    if not m: continue
    uri, cat, cls = m.group(1), f.split('/')[-2], os.path.basename(f)[:-3]
    key = (cat, cls[:-len('Request')])
    lib_calls[key] = uri
    if key in game_calls: game_calls[key]['uri'] = uri  # 真实路径不一定等于 目录/类名
    for code in api_code.values():
        if re.search(rf'\b{cls}\b', code) and (f'ApiInterface.{cat}' in code or f'{cat}.{cls}' in code):
            backend_used.add(key)
            break
frontend_used = set()
for f in glob.glob(f'{WEB}/**/*.ts*', recursive=True):
    if f.endswith('ortega-client.ts') or '/generated/' in f: continue
    frontend_used |= {f'{c}/{m}' for c, m in re.findall(r'ortegaApi\.(\w+)\.(\w+)\(', open(f).read())}
repo_mbs = sorted(os.path.basename(f)[:-3] for f in glob.glob(f'{ROOT}/MementoMori.Ortega/Share/Master/Data/*MB.cs'))
repo_hubs = sorted(set(re.findall(r'IMagicOnion\w+Receiver', ''.join(open(f, encoding='utf-8-sig').read() for f in glob.glob(f'{ROOT}/MementoMori.Api/Handlers/LocalRaid/*.cs')))))

# ---- server master catalog (what the CDN actually ships right now)
m = re.search(r'MasterVersion: (\d+)', open(API_LOG).read()) if API_LOG else None
ver = m.group(1) if m else None
catalog = urllib.request.urlopen(f'https://cdn-mememori.akamaized.net/master/prd1/version/{ver}/master-catalog').read() if ver else b''

# ---- report
def status(key):
    if key not in lib_calls: return 'missing'
    if key in backend_used or lib_calls[key] in frontend_used: return 'used'
    return 'unused'

by_cat = {}
for key, c in sorted(game_calls.items()):
    by_cat.setdefault(c['category'], []).append(key)
counts = {k: sum(1 for u in game_calls if status(u) == k) for k in ('used', 'unused', 'missing')}
removed = sorted(u for k, u in lib_calls.items() if k not in game_calls and k[0] != 'Debug')

L = ['# Game coverage', '',
     f'Generated by `tools/game_coverage.py` from the Steam client metadata. {len(game_calls)} API calls in the game (debug excluded):',
     f'**{counts["used"]} used** by the helper, **{counts["unused"]} defined but not wired to anything**, **{counts["missing"]} missing**.', '',
     '- **used**: called by an API handler/job/autopilot or by a React page',
     '- **unused**: request/response classes exist in MementoMori.Ortega, nothing calls them yet (cheap to add)',
     '- **missing**: no classes at all; field lists are in `game-coverage.json` to write them', '',
     '## By area', '', '| Area | used | unused | missing | missing calls |', '|---|---|---|---|---|']
for cat, uris in sorted(by_cat.items(), key=lambda kv: -sum(status(u) == 'missing' for u in kv[1])):
    st = [status(u) for u in uris]
    miss = ', '.join(f'`{lower1(k[1])}`' for k in uris if status(k) == 'missing')
    L.append(f'| {cat} | {st.count("used")} | {st.count("unused")} | {st.count("missing")} | {miss} |')
L += ['', '## Defined but unused', '', ', '.join(f'`{c["uri"]}`' for k, c in sorted(game_calls.items()) if status(k) == 'unused') or '-', '',
      '## In the helper but gone from the game', '', ', '.join(f'`{u}`' for u in removed) or '-', '',
      '## Master tables', '',
      f'Game client: {len(game_mbs)} tables. Server catalog (version {ver or "?"}): ' + (f'{sum(m.encode() in catalog for m in game_mbs)} of them shipped.' if catalog else 'not checked.'), '',
      '- Missing classes in MementoMori.Ortega: ' + (', '.join(f'`{m}`' for m in game_mbs if m not in repo_mbs) or '-'),
      '- In the client but not on the server: ' + (', '.join(f'`{m}`' for m in game_mbs if catalog and m.encode() not in catalog) or '-'),
      '- In the helper but removed from the game (load as empty tables): ' + ', '.join(f'`{m}`' for m in repo_mbs if m not in game_mbs and not m.startswith('TextResource')), '',
      '## Real-time (MagicOnion) hubs', '',
      '| Receiver | handled |', '|---|---|'] + [f'| `{h}` | {"yes" if h in repo_hubs else "no"} |' for h in game_hubs]

os.makedirs(f'{ROOT}/docs', exist_ok=True)
open(f'{ROOT}/docs/game-coverage.md', 'w').write('\n'.join(L) + '\n')
json.dump({'calls': {c['uri']: {**c, 'status': status(k)} for k, c in game_calls.items()}, 'masters': game_mbs, 'hubs': game_hubs},
          open(f'{ROOT}/docs/game-coverage.json', 'w'), indent=1, ensure_ascii=False)
print(counts, len(game_mbs), 'tables', len(game_hubs), 'hubs')
